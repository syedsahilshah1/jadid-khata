<?php

namespace Modules\Superadmin\Entities;

use Illuminate\Database\Eloquent\Model;

class AffiliateReferral extends Model
{
    protected $guarded = ['id'];

    /**
     * The attributes that should be cast to native types.
     *
     * @var array
     */
    protected $casts = [
        'registered_at' => 'datetime',
        'cookie_expiry' => 'datetime',
    ];

    /**
     * Get the user owning the affiliate account credited with the referral.
     */
    public function affiliateUser()
    {
        return $this->belongsTo(\App\User::class, 'affiliate_user_id');
    }

    /**
     * Get the business that registered through the referral link.
     */
    public function business()
    {
        return $this->belongsTo(\App\Business::class, 'referred_business_id');
    }

    /**
     * Get the commissions generated by this referred business.
     */
    public function commissions()
    {
        return $this->hasMany(AffiliateCommission::class, 'referred_business_id', 'referred_business_id');
    }
}
